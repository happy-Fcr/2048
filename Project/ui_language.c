static void UI_DrawGlyph(uint16_t x, uint16_t y, uint8_t glyph, uint16_t fg, uint16_t bg)
{
    uint8_t row, col;
    uint8_t bits;

    for (row = 0U; row < 16U; row++) {
        bits = glyphs[glyph][row * 2U];
        for (col = 0U; col < 8U; col++) {
            LCD_DrawPoint(x + col, y + row, (bits & (0x80U >> col)) ? fg : bg);
        }
        bits = glyphs[glyph][row * 2U + 1U];
        for (col = 0U; col < 8U; col++) {
            LCD_DrawPoint(x + col + 8U, y + row, (bits & (0x80U >> col)) ? fg : bg);
        }
    }
}

void UI_SetLanguage(uint8_t language)
{
    ui_language = (language == UI_LANG_CHINESE) ? UI_LANG_CHINESE : UI_LANG_ENGLISH;
}

uint8_t UI_GetLanguage(void)
{
    return ui_language;
}

void UI_ShowText(uint16_t x, uint16_t y, uint8_t text_id, uint16_t fg, uint16_t bg)
{
    static const char *const english_text[] = {"SETTINGS", "VOLUME", "LANGUAGE", "CHINESE", "ENGLISH", "EXIT", "EASY", "NORMAL", "HARD", "RANK", "YOU WIN", "GAME OVER", "SCORE", "DIFFICULTY"};
    uint8_t i;

    if (ui_language == UI_LANG_ENGLISH) {
        LCD_ShowString(x, y, english_text[text_id], fg, bg);
        return;
    }

    for (i = 0U; i < text_length[text_id]; i++) {
        UI_DrawGlyph(x + (uint16_t)i * 17U, y, text_glyphs[text_id][i], fg, bg);
    }
}

void UI_ShowStartItem(uint16_t x, uint16_t y, uint8_t item, uint8_t selected,
                      uint16_t fg, uint16_t bg)
{
    static const char *const english_items[] = {"START GAME", "RANK", "DIFFICULTY", "SETTINGS", "EXIT"};
    uint8_t i;

    LCD_ShowString(x, y, selected ? ">" : " ", fg, bg);
    if (ui_language == UI_LANG_ENGLISH) {
        LCD_ShowString(x + 12U, y, english_items[item], fg, bg);
        return;
    }

    for (i = 0U; i < 2U; i++) {
        UI_DrawGlyph(x + 18U + (uint16_t)i * 17U, y, start_text[item][i], fg, bg);
    }
}
